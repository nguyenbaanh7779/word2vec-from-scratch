"""
Regenerate the figures and tables used by report/ and slides/ from the outputs of the demo and final runs,
so that every reported number comes from output/<run>/config.json and output/<run>/evaluation.json.

Usage (after experiments/run_demo.sh and experiments/run_final.sh):
    python experiments/make_report_assets.py
"""
import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.append(str(ROOT / "src"))

import numpy as np

from config import OUTPUT_DIR
from evaluation.evaluate import (GROUP_STYLES, INK, INK_MUTED, N_BASELINE_WORDS, NEIGHBOUR_QUERIES,
                                 load_run_models, plot_pca, style_axes)

import matplotlib
matplotlib.use("Agg")
# fixed PDF timestamps, so regenerating unchanged figures leaves the files byte-identical
os.environ.setdefault("SOURCE_DATE_EPOCH", "0")
import matplotlib.pyplot as plt

FIG_DIR = ROOT / "report" / "figures"
GEN_DIR = ROOT / "report" / "generated"

# SIMILARITY_PAIRS in evaluate.py lists the related pairs first, then the unrelated control pairs
N_RELATED_PAIRS = 6


def load_run(run_name: str) -> dict:
    run_dir = OUTPUT_DIR / run_name
    loss = np.load(run_dir / f"loss_{run_name}.npz")
    return {
        "name": run_name,
        "config": json.loads((run_dir / "config.json").read_text()),
        "eval": json.loads((run_dir / "evaluation.json").read_text()),
        "steps": loss["steps"],
        "losses": loss["losses"],
    }


def fmt_int(x: float) -> str:
    return f"{int(x):,}"


def fmt2(x: float) -> str:
    "Two decimals for LaTeX text: no negative zero, and a proper minus sign"
    return f"{x:.2f}".replace("-0.00", "0.00").replace("-", "$-$")


def fmt_cos(entry: dict) -> str:
    return "OOV" if entry["cosine"] is None else f"{fmt2(entry['cosine'])} (p{entry['percentile']:.0f})"


def fmt_rank(entry: dict) -> str:
    if entry["top5"] is None:
        return "OOV"
    return str(entry["rank"]) if entry["rank"] else "$>$10"


def write(name: str, text: str) -> None:
    (GEN_DIR / name).write_text("% Generated by experiments/make_report_assets.py; do not edit by hand.\n" + text)


# ---- figures ----

def plot_loss_curves(runs: list[dict], out_path: Path, figsize: tuple[float, float] = (6.4, 3.0)) -> None:
    "Windowed training loss of each run against training progress measured in epochs"
    fig, ax = plt.subplots(figsize=figsize)
    for run, (color, _) in zip(runs, GROUP_STYLES):
        cfg = run["config"]["hyperparameters"]
        steps_per_epoch = run["steps"][-1] / cfg["epochs"]
        x = run["steps"] / steps_per_epoch
        label = f"{run['name']}: {cfg['max_tokens'] / 1e6:.0f}M tokens (mean of {cfg['report_every']:,} steps)"
        ax.plot(x, run["losses"], color=color, linewidth=2, label=label)
        ax.annotate(f"{run['losses'][-1]:.2f}", (x[-1], run["losses"][-1]), xytext=(4, 0),
                    textcoords="offset points", va="center", fontsize=8, color=INK)
    for boundary in range(1, runs[0]["config"]["hyperparameters"]["epochs"]):
        ax.axvline(boundary, color=INK_MUTED, linewidth=0.8, linestyle=":")
    style_axes(ax)
    ax.set_xlabel("Training progress (epochs)", fontsize=9)
    ax.set_ylabel("Mean loss per window", fontsize=9)
    ax.legend(fontsize=8, frameon=False, labelcolor=INK)
    fig.tight_layout()
    fig.savefig(out_path)
    plt.close(fig)


# ---- tables and macros ----

def macros(runs: dict[str, dict]) -> str:
    "\\newcommand definitions for every number quoted in the text, e.g. \\FinalVocab"
    lines = []
    def define(name, value): lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    for key, run in runs.items():
        prefix = key.capitalize()
        cfg, ev = run["config"], run["eval"]
        hp, data, res = cfg["hyperparameters"], cfg["data"], cfg["results"]
        trained, untrained = ev["trained"], ev["untrained"]
        steps = res["loss_history"][-1][0]
        base = trained["random_pair_cosine"][f"top_{N_BASELINE_WORDS}"]

        env = cfg["environment"]
        define(f"{prefix}Python", env["python"])
        define(f"{prefix}Numpy", env["numpy"])
        define(f"{prefix}Commit", f"\\texttt{{{(env['git']['commit'] or 'unknown')[:7]}}}")
        define(f"{prefix}Tokens", fmt_int(hp["max_tokens"]))
        define(f"{prefix}TokensShort", f"{hp['max_tokens'] / 1e6:.0f}M")
        define(f"{prefix}Vocab", fmt_int(data["vocab_size"]))
        define(f"{prefix}KeptTokens", fmt_int(data["tokens_after_subsampling"]))
        define(f"{prefix}KeptPct", f"{100 * data['tokens_after_subsampling'] / hp['max_tokens']:.0f}\\%")
        define(f"{prefix}Steps", fmt_int(steps))
        define(f"{prefix}StepsMillions", f"{steps / 1e6:.1f}M")
        define(f"{prefix}TrainMinutes", f"{res['train_time_s'] / 60:.1f}")
        define(f"{prefix}StepsPerSec", fmt_int(round(steps / res["train_time_s"], -2)))
        for i, word in enumerate(["One", "Two", "Three", "Four", "Five"][:len(res["epoch_losses"])]):
            define(f"{prefix}LossEpoch{word}", f"{res['epoch_losses'][i]:.3f}")
        define(f"{prefix}LossFirstWindow", f"{res['loss_history'][0][1]:.2f}")
        define(f"{prefix}LossLastWindow", f"{res['loss_history'][-1][1]:.2f}")
        define(f"{prefix}BaselineMean", f"{base['mean']:.2f}")
        define(f"{prefix}BaselineStd", f"{base['std']:.2f}")
        define(f"{prefix}BaselineAllMean", f"{trained['random_pair_cosine']['all_words']['mean']:.2f}")
        define(f"{prefix}UntrainedBaselineMean", fmt2(untrained["random_pair_cosine"][f"top_{N_BASELINE_WORDS}"]["mean"]))
        define(f"{prefix}Answerable", trained["analogy_summary"]["answerable"])
        define(f"{prefix}HitOne", trained["analogy_summary"]["hit@1"])
        define(f"{prefix}HitFive", trained["analogy_summary"]["hit@5"])
        define(f"{prefix}UntrainedHitFive", untrained["analogy_summary"]["hit@5"])

        related = [p for p in trained["pairs"][:N_RELATED_PAIRS] if p["cosine"] is not None]
        controls = [p for p in trained["pairs"][N_RELATED_PAIRS:] if p["cosine"] is not None]
        define(f"{prefix}RelatedPctMin", f"{min(p['percentile'] for p in related):.0f}")
        define(f"{prefix}RelatedPctMax", f"{max(p['percentile'] for p in related):.0f}")
        define(f"{prefix}ControlPctMin", f"{min(p['percentile'] for p in controls):.0f}")
        define(f"{prefix}ControlPctMax", f"{max(p['percentile'] for p in controls):.0f}")

    define("BaselineWords", fmt_int(N_BASELINE_WORDS))
    return "\n".join(lines) + "\n"


def hyperparameter_table(demo: dict, final: dict) -> str:
    hd, hf = demo["config"]["hyperparameters"], final["config"]["hyperparameters"]
    rows = [
        ("Tokens of text8 used", f"{fmt_int(hd['max_tokens'])} (demo) / {fmt_int(hf['max_tokens'])} (final)", "\\texttt{--max-tokens}"),
        ("Minimum word count", hf["min_count"], "\\texttt{--min-count}"),
        ("Subsampling threshold $t$", f"{hf['subsample_t']:g}", "\\texttt{--subsample-t}"),
        ("Embedding dimension $d$", hf["embed_dim"], "\\texttt{--embed-dim}"),
        ("Epochs", hf["epochs"], "\\texttt{--epochs}"),
        ("Maximum window size", hf["max_window"], "\\texttt{--max-window}"),
        ("Negative samples $K$", hf["n_negatives"], "\\texttt{--n-negatives}"),
        ("Noise distribution exponent", hf["noise_power"], "fixed"),
        ("Initial / minimum learning rate", f"{hf['start_lr']:g} / {hf['lr_min']:g}", "\\texttt{--start-lr}, \\texttt{--lr-min}"),
        ("Loss report interval (steps)", f"{fmt_int(hd['report_every'])} / {fmt_int(hf['report_every'])}", "\\texttt{--report-every}"),
        ("Random seed", hf["seed"], "\\texttt{--seed}"),
    ]
    body = "\n".join(f"{a} & {b} & {c} \\\\" for a, b, c in rows)
    return ("\\begin{tabular}{lll}\n" + "\\toprule\nHyperparameter & Value & CLI option \\\\\n\\midrule\n"
            + body + "\n\\bottomrule\n\\end{tabular}\n")


def runs_table(demo: dict, final: dict) -> str:
    def row(label, f): return f"{label} & {f(demo)} & {f(final)} \\\\"
    def steps(r): return r["config"]["results"]["loss_history"][-1][0]
    def time_s(r): return r["config"]["results"]["train_time_s"]
    def base(r): return r["eval"]["trained"]["random_pair_cosine"][f"top_{N_BASELINE_WORDS}"]
    def hits(r): s = r["eval"]["trained"]["analogy_summary"]; return f"{s['hit@1']} / {s['hit@5']} of {s['answerable']}"
    rows = [
        row("Tokens of text8", lambda r: fmt_int(r["config"]["hyperparameters"]["max_tokens"])),
        row("Vocabulary size", lambda r: fmt_int(r["config"]["data"]["vocab_size"])),
        row("Tokens after subsampling", lambda r: fmt_int(r["config"]["data"]["tokens_after_subsampling"])),
        row("Training steps (pairs)", lambda r: fmt_int(steps(r))),
        row("Training time", lambda r: f"{time_s(r) / 60:.1f} min"),
        row("Throughput (steps/s)", lambda r: fmt_int(round(steps(r) / time_s(r), -2))),
        "\\midrule",
    ]
    for i in range(len(final["config"]["results"]["epoch_losses"])):
        rows.append(row(f"Mean loss, epoch {i + 1}", lambda r, i=i: f"{r['config']['results']['epoch_losses'][i]:.3f}"))
    rows += [
        "\\midrule",
        row(f"Random-pair cosine (top {fmt_int(N_BASELINE_WORDS)})", lambda r: f"{fmt2(base(r)['mean'])} $\\pm$ {fmt2(base(r)['std'])}"),
        row("Analogies: hit@1 / hit@5", hits),
    ]
    return ("\\begin{tabular}{lrr}\n\\toprule\n & Demo & Final \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n")


def neighbours_table(final: dict, top_trained: int, top_untrained: int) -> str:
    trained, untrained = final["eval"]["trained"]["neighbours"], final["eval"]["untrained"]["neighbours"]
    def words(entry, k): return "OOV" if entry is None else ", ".join(w for w, _ in entry[:k])
    if top_untrained:
        head = f"Query & Trained (top {top_trained}) & Untrained (top {top_untrained}) \\\\"
        rows = [f"\\textit{{{q}}} & {words(trained[q], top_trained)} & {words(untrained[q], top_untrained)} \\\\" for q in NEIGHBOUR_QUERIES]
        spec = "l>{\\raggedright\\arraybackslash}p{0.5\\linewidth}>{\\raggedright\\arraybackslash}p{0.28\\linewidth}"
    else:
        head = f"Query & Nearest neighbours (top {top_trained}) \\\\"
        rows = [f"\\textit{{{q}}} & {words(trained[q], top_trained)} \\\\" for q in NEIGHBOUR_QUERIES]
        spec = "ll"
    return (f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{head}\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n")


def cosine_table(demo: dict, final: dict) -> str:
    rows = []
    pairs = zip(demo["eval"]["trained"]["pairs"], final["eval"]["trained"]["pairs"], final["eval"]["untrained"]["pairs"])
    for i, (d, f, u) in enumerate(pairs):
        if i == N_RELATED_PAIRS:
            rows.append("\\midrule")
        a, b = f["pair"]
        rows.append(f"\\textit{{{a}}} -- \\textit{{{b}}} & {fmt_cos(d)} & {fmt_cos(f)} & {fmt_cos(u)} \\\\")
    return ("\\begin{tabular}{lrrr}\n\\toprule\nPair & Demo (1M) & Final (5M) & Untrained \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def analogy_table(demo: dict, final: dict, with_answers: bool = True) -> str:
    rows = []
    entries = zip(demo["eval"]["trained"]["analogies"], final["eval"]["trained"]["analogies"], final["eval"]["untrained"]["analogies"])
    for d, f, u in entries:
        a, b, c = f["query"]
        query = f"\\textit{{{a}}} : \\textit{{{b}}} :: \\textit{{{c}}} : ?"
        answers = "OOV" if f["top5"] is None else ", ".join(f["top5"][:3])
        cells = [query, f"\\textit{{{f['expected']}}}"] + ([answers] if with_answers else []) + [fmt_rank(f), fmt_rank(d), fmt_rank(u)]
        rows.append(" & ".join(cells) + " \\\\")
    head = ["Analogy", "Expected"] + (["Final: top 3"] if with_answers else []) + ["Final", "Demo", "Untrained"]
    spec = "ll" + ("l" if with_answers else "") + "rrr"
    return (f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n & & {'& ' if with_answers else ''}\\multicolumn{{3}}{{c}}{{Rank of expected}} \\\\\n"
            + f"\\cmidrule(l){{{len(head) - 2}-{len(head)}}}\n" + " & ".join(head) + " \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--demo-run", default="demo")
    parser.add_argument("--final-run", default="final")
    args = parser.parse_args()

    FIG_DIR.mkdir(parents=True, exist_ok=True)
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    demo, final = load_run(args.demo_run), load_run(args.final_run)

    plot_loss_curves([demo, final], FIG_DIR / "loss_curves.pdf")
    # smaller canvases for the slides, so that the text stays legible when the figure fills half a slide
    plot_loss_curves([demo, final], FIG_DIR / "loss_curves_slides.pdf", figsize=(4.4, 2.9))
    model, untrained, _ = load_run_models(args.final_run)
    tokens = f"{final['config']['hyperparameters']['max_tokens'] / 1e6:.0f}M tokens"
    plot_pca({f"Trained ({tokens})": model, "Untrained (initialisation)": untrained}, FIG_DIR / "pca_final.pdf")
    plot_pca({f"Trained ({tokens})": model}, FIG_DIR / "pca_final_trained.pdf", panel_size=(3.8, 3.3))

    write("macros.tex", macros({"demo": demo, "final": final}))
    write("hyperparameters.tex", hyperparameter_table(demo, final))
    write("runs.tex", runs_table(demo, final))
    write("neighbours.tex", neighbours_table(final, top_trained=8, top_untrained=3))
    write("neighbours_short.tex", neighbours_table(final, top_trained=4, top_untrained=0))
    write("cosine.tex", cosine_table(demo, final))
    write("analogies.tex", analogy_table(demo, final))
    write("analogies_short.tex", analogy_table(demo, final, with_answers=False))

    print(f"Wrote figures to {FIG_DIR} and tables to {GEN_DIR}")


if __name__ == "__main__":
    main()
